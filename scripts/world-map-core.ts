// What the world map is made of, as pure functions: the dots of `app/ui/map/world-dots.svg` (the land and water outlines of world-map-data.ts, sampled every 2.5°), the table of
// `app/server/countries.ts` (each country's name, its point in the same box, and the place of its name in English alphabetical order), and the two files' text. The command
// (world-map.ts) writes them and `pnpm map:check` compares them; the test (world-map.test.ts) imports this file for both, and so cannot run the command by importing it.
//
// The projection is the mock kit's, kept exactly: equirectangular into a box of 1000 × 378, longitude −180…180, latitude 78…−58. Nothing here reads the network, a clock or
// anything but the committed outputs; `Intl.Collator` is the one thing that depends on the Node that writes (`order`), and `engines` says Node 24.

import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

import { COUNTRY_POINTS, LAND, WATER } from "./world-map-data";

export const VIEW_BOX = "0 0 1000 378";
/** Box units to a degree. */
export const K = 1000 / 360;
const HEIGHT = 378;
/** The size of a cell of the dot grid, in degrees. */
const CELL = 2.5;
/** The latitude of the first row's centres, and the last latitude a row's centre may have (the box ends at −58°). */
const FIRST_ROW = 76.75;
const LAST_LAT = -58;
const FIRST_COLUMN = -178.75;

type Polygon = readonly (readonly [number, number])[];

/** Whether the point is inside the polygon, by even-odd ray casting: a ray towards +longitude crosses its edges an odd number of times. */
function inside(lon: number, lat: number, polygon: Polygon): boolean {
  let crossings = false;
  for (let at = 0, last = polygon.length - 1; at < polygon.length; last = at++) {
    const [x1, y1] = polygon[at]!;
    const [x2, y2] = polygon[last]!;
    if (y1 > lat !== y2 > lat && lon < ((x2 - x1) * (lat - y1)) / (y2 - y1) + x1) crossings = !crossings;
  }
  return crossings;
}

/** Whether a point is in a `LAND` polygon and in no `WATER` polygon. */
export function isLand(lon: number, lat: number): boolean {
  return Object.values(LAND).some((polygon) => inside(lon, lat, polygon)) && !Object.values(WATER).some((polygon) => inside(lon, lat, polygon));
}

/** A coordinate in the box, to one decimal, as a number. */
const oneDecimal = (value: number): number => Number(value.toFixed(1));

/** The point of a latitude and a longitude in the box: `y` is held to 0…378 (Antarctica sits on the bottom edge). */
export function pointOf(lat: number, lon: number): { x: number; y: number } {
  return { x: oneDecimal((lon + 180) * K), y: oneDecimal(Math.min(HEIGHT, Math.max(0, (78 - lat) * K))) };
}

/** The path of the dots: every 2.5° cell centre on land, row by row from latitude 76.75, as `M{x} {y}h0` (a zero-length segment, drawn round). */
export function dotsPath(): string {
  const segments: string[] = [];
  for (let lat = FIRST_ROW; lat > LAST_LAT; lat -= CELL) {
    for (let column = 0; column < 360 / CELL; column++) {
      const lon = FIRST_COLUMN + column * CELL;
      if (!isLand(lon, lat)) continue;
      segments.push(`M${((lon + 180) * K).toFixed(1)} ${((78 - lat) * K).toFixed(1)}h0`);
    }
  }
  return segments.join("");
}

const GENERATED = "scripts/world-map.ts (pnpm map:sync): do not edit.";

/** The whole text of `app/ui/map/world-dots.svg`. */
export function worldDotsSvg(): string {
  return [
    `<!-- Generated by ${GENERATED} -->`,
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${VIEW_BOX}"><path id="dots" d="${dotsPath()}" fill="none" stroke="currentColor" stroke-width="3.4" stroke-linecap="round"/></svg>`,
    "",
  ].join("\n");
}

/** The whole text of `app/server/countries.ts`: a line per code in code order, with the place of the name in English alphabetical order. */
export function countriesModule(): string {
  const collator = new Intl.Collator("en");
  const byName = [...COUNTRY_POINTS].sort(([, a], [, b]) => collator.compare(a, b));
  const order = new Map(byName.map(([code], at) => [code, at]));
  const lines = [...COUNTRY_POINTS]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([code, name, lat, lon]) => {
      const { x, y } = pointOf(lat, lon);
      return `  ${code}: { name: ${JSON.stringify(name)}, x: ${x}, y: ${y}, order: ${order.get(code)} },`;
    });
  return [
    `// Generated by ${GENERATED}`,
    // `| undefined`: D8 may serve a code newer than this table, and without `noUncheckedIndexedAccess` the compiler would let `COUNTRIES[code].name` through.
    "export const COUNTRIES: Readonly<Record<string, { name: string; x: number; y: number; order: number } | undefined>> = {",
    ...lines,
    "};",
    "export const COUNTRY_CODES: ReadonlySet<string> = new Set(Object.keys(COUNTRIES));",
    "",
  ].join("\n");
}

/** The two generated files: their paths from the repository root, and what each should hold. */
export const OUTPUTS: readonly { path: string; text: () => string }[] = [
  { path: "app/ui/map/world-dots.svg", text: worldDotsSvg },
  { path: "app/server/countries.ts", text: countriesModule },
];

/** The paths of the outputs whose file under `root` is missing or is not what the generator would write. */
export function staleOutputs(root: string): string[] {
  return OUTPUTS.filter(({ path, text }) => {
    const file = join(root, path);
    return !existsSync(file) || readFileSync(file, "utf8") !== text();
  }).map(({ path }) => path);
}
